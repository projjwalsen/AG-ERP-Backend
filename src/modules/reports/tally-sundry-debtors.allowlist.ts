export const normalizeTallySundryDebtorName = (value: unknown) =>
    String(value ?? "")
        .normalize("NFKD")
        .replace(/[\u0300-\u036f]/g, "")
        .replace(/[\u2013\u2014\u2212]/g, "-")
        .replace(/\s*-\s*Sundry\s+Debtor\s*$/i, "")
        .replace(/\bPRIVATE\b/gi, "PVT")
        .replace(/\bLIMITED\b/gi, "LTD")
        .replace(/[^a-z0-9]/gi, "")
        .toUpperCase();

export const TALLY_SUNDRY_DEBTOR_ALLOWLIST = new Set(
    TALLY_SUNDRY_DEBTOR_NAMES.map(normalizeTallySundryDebtorName)
);
